"""
    AHPCSpinPairMatrixElement

Store overlap, electronic one-body, and two-body contributions from one AHPC spin-pair contraction.
Overlap is dimensionless, Hamiltonian terms use the integral energy unit, values are CPU scalars, and construction performs no CUDA work.
"""
struct AHPCSpinPairMatrixElement{T<:AbstractFloat}
    overlap::T
    one_body::T
    two_body::T
end
